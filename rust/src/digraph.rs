#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn complete_table_and_original_duplicate_order() {
        assert_eq!(DIGRAPHS.len(), 1894);
        assert_eq!(
            DIGRAPHS.iter().map(|entry| entry.name.len()).max(),
            Some(MAX_DIGRAPH_LENGTH)
        );
        assert_eq!(digraph("N->"), Some('\u{1e4a}'));
        assert_eq!(digraph("S.-."), Some('\u{1e68}'));
        assert_eq!(
            DIGRAPHS.iter().filter(|entry| entry.name == "N->").count(),
            2
        );
    }

    #[test]
    fn every_table_entry_respects_first_prefix_match() {
        for entry in DIGRAPHS {
            let first = DIGRAPHS
                .iter()
                .find(|candidate| candidate.name.starts_with(entry.name))
                .unwrap();
            let expected = if first.name == entry.name {
                Lookup::Found(first.character)
            } else {
                Lookup::Prefix
            };
            assert_eq!(lookup(entry.name.as_bytes()), expected, "{}", entry.name);
        }
    }

    #[test]
    fn common_control_and_long_mnemonics() {
        assert_eq!(digraph("SP"), Some(' '));
        assert_eq!(digraph("NU"), Some('\0'));
        assert_eq!(digraph("a:"), Some('ä'));
        assert!(
            DIGRAPHS
                .iter()
                .any(|entry| entry.name.len() == 7 && digraph(entry.name) == Some(entry.character))
        );
        assert_eq!(lookup(b"a"), Lookup::Prefix);
        assert_eq!(lookup(b""), Lookup::Prefix);
        assert_eq!(lookup(b"not-a-digraph"), Lookup::Unknown);
        assert_eq!(lookup(&[0xff]), Lookup::Unknown);
        assert_eq!(lookup(b"SP\0ignored"), Lookup::Found(' '));
    }
}

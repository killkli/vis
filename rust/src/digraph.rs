pub const MAX_DIGRAPH_LENGTH: usize = 7;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Digraph {
    pub name: &'static str,
    pub character: char,
    pub description: &'static str,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Lookup {
    Found(char),
    Prefix,
    Unknown,
}

/// Match an exact mnemonic, preserving the original table's lookup ordering.
pub fn digraph(name: &str) -> Option<char> {
    match lookup(name.as_bytes()) {
        Lookup::Found(character) => Some(character),
        Lookup::Prefix | Lookup::Unknown => None,
    }
}

/// Byte-based lookup also handles non-UTF-8 command-line and input bytes.
/// Like the original C interface, a NUL terminates the supplied name.
pub fn lookup(name: &[u8]) -> Lookup {
    let end = name
        .iter()
        .position(|byte| *byte == 0)
        .unwrap_or(name.len());
    let name = &name[..end];
    for entry in DIGRAPHS {
        if entry.name.as_bytes().starts_with(name) {
            return if entry.name.len() == name.len() {
                Lookup::Found(entry.character)
            } else {
                Lookup::Prefix
            };
        }
    }
    Lookup::Unknown
}

const fn entry(name: &'static str, character: char, description: &'static str) -> Digraph {
    Digraph {
        name,
        character,
        description,
    }
}

